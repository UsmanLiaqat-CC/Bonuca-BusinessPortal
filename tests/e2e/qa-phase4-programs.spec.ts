import { expect, test } from '@playwright/test'
import { login, shot, upload } from './helpers'

/** QA Phase 4 — Spec §4.2 Loyalty Programs: every setup field, conditional field, lifecycle, campaigns. */
test.describe('Phase 4 · §4.2 programs & campaigns', () => {
  test.beforeEach(async ({ page }) => login(page, 'owner'))

  test('Stamp Card: all fields, conditional expiry, icon set, contrast suggestion, publish → QR, lifecycle', async ({ page }) => {
    await page.goto('/app/programs')
    await page.getByRole('button', { name: /Create Program/ }).click()
    await expect(page.getByRole('dialog').getByRole('button')).toContainText(['Stamp Card', 'Membership Card', 'Tier Program', 'Points Program'])
    await page.getByRole('dialog').getByRole('button', { name: 'Stamp Card' }).click()
    await page.getByLabel('Program Name').fill('QA Stamp')
    await upload(page, 'Program Logo')
    await upload(page, 'Program Icon')
    await upload(page, 'Hero / Strip Image')
    // Background: colour OR image (radio), never both
    await page.getByRole('radio', { name: 'Flat colour (RGB)' }).click()
    await page.getByLabel('Background colour', { exact: true }).fill('#F4F4F4')
    await expect(page.getByText(/Low contrast|Suggested for contrast/)).toBeVisible()
    await page.getByRole('button', { name: /^Use #/ }).click()
    await page.getByRole('radio', { name: 'Background image' }).click()
    await expect(page.getByLabel('Background colour', { exact: true })).toHaveCount(0)
    await upload(page, 'Background image')
    await page.getByLabel('Number of Stamps Required').fill('8')
    for (const icon of ['Star', 'Heart', 'Scissors', 'Croissant', 'Check mark', 'Coffee cup (default)']) await page.getByRole('radio', { name: icon }).click()
    await page.getByLabel('Reward Description').fill('1 Free Tea')
    await expect(page.getByLabel('Reward Type').locator('option')).toHaveText(['Free item', '% discount', 'Fixed discount', 'Custom'])
    await page.getByLabel('Reward Type').selectOption('custom')
    await page.getByRole('switch', { name: 'Expiry Rule' }).click()
    await page.getByLabel(/Expiry Rule \(days/).fill('60')
    await page.getByLabel('Terms & Conditions').fill('One per visit')
    await expect(page.getByTestId('wallet-pass')).toContainText('QA Stamp')
    await expect(page.getByTestId('wallet-pass')).toContainText('stamps to go')
    await shot(page, 'p4-01-stamp-form')
    await page.getByRole('button', { name: 'Publish', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'QA Stamp' })).toBeVisible()
    await expect(page.getByAltText('QR code: QA Stamp')).toBeVisible()
    // Enable/Disable toggle
    await page.getByRole('switch', { name: 'Enabled' }).click()
    await expect(page.getByText('Paused').first()).toBeVisible()
    await expect(page.getByText(/does not enrol new members/)).toBeVisible()
    await page.getByRole('switch', { name: /Disabled/ }).click()
    await expect(page.getByText('Active').first()).toBeVisible()
    // Archive with confirmation
    await page.getByRole('button', { name: 'Archive' }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Archive' }).click()
    await expect(page.getByText(/permanently retired/)).toBeVisible()
    await shot(page, 'p4-02-stamp-archived')
  })

  test('Draft: Save as draft needs only a name; Publish needs all required fields', async ({ page }) => {
    await page.goto('/app/programs/new/stamp')
    await page.getByRole('button', { name: 'Save as draft' }).click()
    await expect(page.getByText('Program name is required.')).toBeVisible()
    await page.getByLabel('Program Name').fill('QA Draft')
    await page.getByRole('button', { name: 'Save as draft' }).click()
    await expect(page.getByText(/No QR exists yet/)).toBeVisible()
    await page.getByRole('button', { name: 'Publish' }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Publish' }).click()
    await expect(page.getByText(/Complete the required fields/).first()).toBeVisible()
  })

  test('Membership Card: benefit types, discount only for discounts, validity date', async ({ page }) => {
    await page.goto('/app/programs/new/membership')
    await expect(page.getByText(/never track stamps or points/)).toBeVisible()
    await page.getByLabel('Program Name').fill('QA VIP')
    await upload(page, 'Program Logo')
    await page.getByLabel('Benefit Description').fill('15% off')
    await expect(page.getByLabel('Benefit Type').locator('option')).toHaveText(['% discount', 'Fixed discount', 'Perk description only'])
    await page.getByLabel('Discount Value (%)').fill('150')
    await page.getByLabel('Validity').selectOption('expires_on')
    await page.getByRole('button', { name: 'Publish', exact: true }).click()
    await expect(page.getByText('A percentage cannot exceed 100.')).toBeVisible()
    await expect(page.getByText('Choose the expiry date.')).toBeVisible()
    await page.getByLabel('Discount Value (%)').fill('15')
    await page.getByLabel('Expiry date').fill('2027-12-31')
    await page.getByLabel('Benefit Type').selectOption('fixed_discount')
    await expect(page.getByLabel('Discount Value (amount)')).toBeVisible()
    await page.getByLabel('Benefit Type').selectOption('perk')
    await expect(page.getByLabel(/Discount Value/)).toHaveCount(0)
    await expect(page.getByLabel('Validity').locator('option')).toHaveText(['Permanent', 'Expires on date', 'Renews annually'])
    await shot(page, 'p4-03-membership-form')
    await page.getByRole('button', { name: 'Publish', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'QA VIP' })).toBeVisible()
  })

  test('Tier Program: enable tiers, 2–5 tiers with default names, basis, per-tier fields, downgrade', async ({ page }) => {
    await page.goto('/app/programs/new/tier')
    await page.getByLabel('Program Name').fill('QA Club')
    await upload(page, 'Program Logo')
    await expect(page.getByLabel('Number of Tiers').locator('option')).toHaveText(['2', '3', '4', '5'])
    await page.getByLabel('Number of Tiers').selectOption('5')
    const names = page.getByLabel('Tier Name')
    await expect(names).toHaveCount(5)
    await expect(names.nth(4)).toHaveValue('Diamond')
    await expect(page.getByLabel('Upgrade Basis').locator('option')).toHaveText(['Visits', 'Points', 'Total Spend'])
    await page.getByLabel('Upgrade Basis').selectOption('spend')
    await expect(page.getByLabel(/Required Value \(total spend\)/).first()).toBeVisible()
    await page.getByLabel('Number of Tiers').selectOption('3')
    await expect(names).toHaveCount(3)
    for (let i = 0; i < 3; i++) await page.getByLabel('Rewards & Benefits').nth(i).fill(`Perk ${i}`)
    await page.getByRole('switch', { name: 'Downgrade Rule' }).click()
    await page.getByLabel(/Downgrade Rule \(days/).fill('90')
    await shot(page, 'p4-04-tier-form')
    await page.getByRole('switch', { name: 'Enable Tiers' }).click()
    await expect(page.getByLabel('Number of Tiers')).toHaveCount(0)
    await page.getByRole('switch', { name: 'Enable Tiers' }).click()
    await page.getByRole('button', { name: 'Publish', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'QA Club' })).toBeVisible()
  })

  test('Points Program: currency list + other, ratio, fixed/manual, rounding, min, cap, rewards list, expiries', async ({ page }) => {
    await page.goto('/app/programs/new/points')
    await page.getByLabel('Program Name').fill('QA Points')
    await upload(page, 'Program Logo')
    await expect(page.getByLabel('Currency').locator('option')).toHaveText(['EUR', 'USD', 'GBP', 'CZK', 'TRY', 'CHF', 'PLN', 'Other'])
    await page.getByLabel('Currency').selectOption('other')
    await page.getByLabel('Currency code').fill('SEK')
    await page.getByLabel('Spend amount').fill('1')
    await page.getByLabel('Points earned').fill('5')
    await page.getByLabel('Awarding Method').selectOption('fixed')
    await page.getByLabel('Points per scan').fill('20')
    await page.getByLabel('Awarding Method').selectOption('manual')
    await expect(page.getByLabel('Points per scan')).toHaveCount(0)
    await expect(page.getByLabel('Rounding Rule').locator('option')).toHaveText(['Round down', 'Round up', 'Round to nearest'])
    await page.getByLabel('Rounding Rule').selectOption('nearest')
    await page.getByLabel(/Minimum Purchase Amount/).fill('3')
    await page.getByLabel(/Maximum Points per Transaction/).fill('400')
    await page.getByLabel('Reward 1 name').fill('Free Coffee')
    await page.getByLabel('Points Required').first().fill('100')
    await page.getByRole('button', { name: 'Add reward' }).click()
    await page.getByLabel('Reward 2 name').fill('Free Cake')
    await page.getByLabel('Points Required').nth(1).fill('250')
    await page.getByRole('button', { name: 'Add reward' }).click()
    await page.getByRole('button', { name: 'Remove reward 3' }).click()
    await page.getByRole('switch', { name: 'Point Expiry' }).click()
    await page.getByLabel(/Point Expiry \(months/).fill('12')
    await page.getByRole('switch', { name: 'Reward Expiry' }).click()
    await page.getByLabel(/Reward Expiry \(days/).fill('30')
    await expect(page.getByTestId('wallet-pass')).toContainText('Next reward')
    await shot(page, 'p4-05-points-form')
    await page.getByRole('button', { name: 'Publish', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'QA Points' })).toBeVisible()
    await expect(page.getByText('SEK').first()).toBeVisible()
  })

  test('Campaigns: acquisition (linked stamp card, starting stamps incl. custom, welcome gift) and voucher (dates, logo, QR)', async ({ page }) => {
    await page.goto('/app/campaigns/new/stamp_acquisition')
    await page.getByLabel('Campaign Name').fill('QA Cup-lid')
    await page.getByLabel('Linked Stamp Card Program').selectOption({ label: 'Coffee Card (active)' })
    await expect(page.getByLabel('Starting Stamps').locator('option')).toHaveText(['0', '1', '2', '3', 'Custom'])
    await page.getByLabel('Starting Stamps').selectOption('custom')
    await page.getByLabel('Custom starting stamps').fill('5')
    await expect(page.getByLabel('Reward Name')).toHaveCount(0)
    await page.getByRole('switch', { name: 'Welcome Gift (optional)' }).click()
    for (const l of ['Reward Name', 'Validity Period (days)', 'Description', 'Redemption Conditions']) await expect(page.getByLabel(l)).toBeVisible()
    await page.getByRole('button', { name: 'Publish & generate QR' }).click()
    await expect(page.getByText('Reward name is required.')).toBeVisible()
    await page.getByLabel('Reward Name').fill('Free cookie')
    await page.getByRole('button', { name: 'Publish & generate QR' }).click()
    await expect(page.getByAltText('QR code: QA Cup-lid')).toBeVisible()
    await expect(page.getByLabel('Print format').locator('option')).toHaveText(['Cup', 'Flyer', 'Sticker', 'Poster'])
    const pdf = page.waitForEvent('download')
    await page.getByRole('button', { name: 'PDF' }).click()
    expect((await pdf).suggestedFilename()).toMatch(/\.pdf$/)
    const png = page.waitForEvent('download')
    await page.getByRole('button', { name: 'PNG' }).click()
    expect((await png).suggestedFilename()).toMatch(/\.png$/)
    await shot(page, 'p4-06-acquisition-campaign')

    await page.goto('/app/campaigns/new/voucher')
    await page.getByLabel('Campaign Name').fill('QA Voucher')
    await page.getByLabel('Voucher Reward').fill('Free Muffin')
    await page.getByLabel('Valid From').fill('2026-11-10')
    await page.getByLabel('Valid To').fill('2026-11-01')
    await page.getByRole('button', { name: 'Publish & generate QR' }).click()
    await expect(page.getByText('Valid To must be on or after Valid From.')).toBeVisible()
    await expect(page.getByText('Logo is required.')).toBeVisible()
    await page.getByLabel('Valid To').fill('2026-12-01')
    await upload(page, 'Logo')
    await expect(page.getByTestId('wallet-pass')).toContainText('Free Muffin')
    await page.getByRole('button', { name: 'Publish & generate QR' }).click()
    await expect(page.getByAltText('QR code: QA Voucher')).toBeVisible()
    await shot(page, 'p4-07-voucher-campaign')
  })

  test('Several programs of the same type + status filters', async ({ page }) => {
    await page.goto('/app/programs')
    await expect(page.getByRole('link', { name: /Coffee Card/ })).toBeVisible()
    await expect(page.getByRole('link', { name: /Lunch Card/ })).toBeVisible()
    await page.getByRole('tab', { name: /Draft/ }).click()
    await expect(page.getByRole('link', { name: /Coffee Card/ })).toHaveCount(0)
    await expect(page.getByRole('link', { name: /Lunch Card/ })).toBeVisible()
    await shot(page, 'p4-08-programs-filter')
  })
})
