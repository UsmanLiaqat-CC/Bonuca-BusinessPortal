import { expect, test } from '@playwright/test'
import { login, shot } from './helpers'

/** QA Phase 7 — Spec §4.5 Customers, §4.7 Notifications, §4.8 Rewards. */
test.describe('Phase 7 · customers, notifications, rewards', () => {
  test.beforeEach(async ({ page }) => login(page, 'owner'))

  test('Customers: search by name / phone / email / ID; profile sections; notes', async ({ page }) => {
    await page.goto('/app/customers')
    const search = page.getByLabel('Search customers')
    const firstRow = page.getByRole('row').nth(1)
    const name = (await firstRow.getByRole('cell').first().textContent())!.trim()
    const id = (await firstRow.getByRole('cell').nth(1).textContent())!.trim()
    await search.fill(id)
    await expect(page.getByRole('row')).toHaveCount(2)
    await search.fill(name.split(' ')[0]!)
    await expect(page.getByRole('row').filter({ hasText: name }).first()).toBeVisible()
    const emailCell = page.getByRole('cell', { name: /@example\.com/ }).first()
    const email = (await emailCell.textContent())!.trim()
    await search.fill(email.toUpperCase())
    await expect(page.getByRole('row').filter({ hasText: email })).toHaveCount(1)
    await search.fill('')
    const phone = (await page.getByRole('cell', { name: /^\+49/ }).first().textContent())!.trim()
    await search.fill(phone.slice(-7))
    await expect(page.getByRole('cell', { name: phone }).first()).toBeVisible()
    await search.fill('zzz-nobody')
    await expect(page.getByText('No matching customers')).toBeVisible()
    await search.fill(id)
    await page.getByRole('row').nth(1).click()
    for (const h of ['Profile', 'Memberships', 'Rewards', 'Notes', 'Visit history']) await expect(page.getByRole('heading', { name: h })).toBeVisible()
    for (const s of ['Number of scans', 'Last visit']) await expect(page.getByText(s)).toBeVisible()
    await page.getByLabel('Notes').fill('QA note')
    await page.getByRole('button', { name: 'Save notes' }).click()
    await expect(page.getByText('Notes saved.')).toBeVisible()
    await shot(page, 'p7-01-customer-profile')
  })

  test('Signup fields configurable; Add customer respects them', async ({ page }) => {
    await page.goto('/app/customers/signup-fields')
    await expect(page.getByRole('radiogroup', { name: 'Name requirement' }).getByRole('radio', { name: 'Required' })).toHaveAttribute('aria-checked', 'true')
    for (const f of ['Email', 'Phone Number', 'Birthday']) await expect(page.getByRole('radiogroup', { name: `${f} requirement` }).getByRole('radio', { name: 'Optional' })).toHaveAttribute('aria-checked', 'true')
    await page.getByRole('radiogroup', { name: 'Email requirement' }).getByRole('radio', { name: 'Required' }).click()
    await page.getByRole('button', { name: 'Save' }).click()
    await expect(page.getByText('Signup fields saved.')).toBeVisible()
    await page.goto('/app/customers')
    await page.getByRole('button', { name: 'Add customer' }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Add customer' }).click()
    await expect(page.getByText('Name is required.')).toBeVisible()
    await expect(page.getByText('Email is required.')).toBeVisible()
    await page.getByLabel('Name').fill('QA Customer')
    await page.getByLabel('Email').fill('qa@example.com')
    await page.getByRole('dialog').getByRole('button', { name: 'Add customer' }).click()
    await expect(page.getByText(/QA Customer added/)).toBeVisible()
    await shot(page, 'p7-02-add-customer')
  })

  test('Notifications: all manual types; draft → edit → send fails truthfully and stays draft', async ({ page }) => {
    await page.goto('/app/notifications')
    await page.getByRole('button', { name: 'New campaign' }).click()
    await expect(page.getByLabel('Campaign type').locator('option')).toHaveText(['Happy Hour', 'New Item', 'Double Stamps', 'Birthday Reward', 'Holiday Campaign', 'Limited Offers', 'Other wallet push notification'])
    await page.getByLabel('Campaign type').selectOption('double_stamps')
    await page.getByLabel('Title').fill('QA Double Stamps')
    await page.getByLabel('Message').fill('Double stamps today!')
    await page.getByLabel('Coffee Card').check()
    await page.getByRole('button', { name: 'Save draft' }).click()
    const row = page.getByRole('listitem').filter({ hasText: 'QA Double Stamps' })
    await expect(row).toContainText('Draft')
    await row.getByRole('button', { name: 'Edit' }).click()
    await page.getByLabel('Title').fill('QA Double Stamps (edited)')
    await page.getByRole('button', { name: 'Save draft' }).click()
    const edited = page.getByRole('listitem').filter({ hasText: 'QA Double Stamps (edited)' })
    await edited.getByRole('button', { name: 'Send' }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Send' }).click()
    await expect(page.getByText(/push notifications is not connected/).first()).toBeVisible()
    await expect(edited).toContainText('Draft')
    await shot(page, 'p7-03-notifications')
  })

  test('Win-back: thresholds with escalating offers, validation, save', async ({ page }) => {
    await page.goto('/app/notifications')
    await page.getByRole('tab', { name: 'Win-back automation' }).click()
    await expect(page.getByRole('switch', { name: 'Enable win-back automation' })).toBeVisible()
    const days = page.getByLabel(/Stage \d — days inactive/)
    await expect(days).toHaveCount(4)
    await expect(days.nth(0)).toHaveValue('14')
    await expect(days.nth(3)).toHaveValue('60')
    await days.nth(1).fill('10')
    await page.getByRole('button', { name: 'Save automation' }).click()
    await expect(page.getByText('Each stage must be later than the previous one.')).toBeVisible()
    await days.nth(1).fill('30')
    await page.getByRole('button', { name: 'Add stage' }).click()
    await page.getByLabel(/Offer/).nth(4).fill('Free lunch')
    await page.getByRole('button', { name: 'Save automation' }).click()
    await expect(page.getByText('Win-back automation saved.')).toBeVisible()
    await expect(page.getByText(/Not delivered/).first()).toBeVisible()
    await shot(page, 'p7-04-winback')
  })

  test('AI Campaigns & AI Bonus Generator: no fabricated draft (service not connected)', async ({ page }) => {
    await page.goto('/app/notifications')
    await page.getByRole('tab', { name: 'AI tools' }).click()
    await page.getByLabel('Prompt').fill('it’s raining today')
    await page.getByRole('button', { name: 'Generate draft' }).first().click()
    await expect(page.getByText('AI service not connected').first()).toBeVisible()
    await page.getByLabel('Goal').fill('more lunch customers')
    await page.getByRole('button', { name: 'Generate draft' }).nth(1).click()
    await expect(page.getByText('AI service not connected')).toHaveCount(2)
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await shot(page, 'p7-05-ai')
  })

  test('Rewards: Available / Redeemed / Pending / Expired; Surprise rewards off by default + config', async ({ page }) => {
    await page.goto('/app/rewards')
    for (const s of ['Available', 'Redeemed', 'Pending', 'Expired']) {
      await page.getByRole('tab', { name: new RegExp(`^${s}`) }).click()
      const rows = page.getByRole('row')
      if ((await rows.count()) > 1) await expect(rows.nth(1)).toContainText(s)
    }
    await page.getByRole('tab', { name: /^Pending/ }).click()
    await expect(page.getByRole('row').nth(1)).toContainText('Pending')
    await shot(page, 'p7-06-rewards')
    await page.getByRole('tab', { name: 'Surprise rewards' }).click()
    const coffee = page.locator('div').filter({ has: page.getByRole('heading', { name: 'Coffee Card' }) }).last()
    await expect(page.getByRole('switch', { name: 'Surprise rewards' }).first()).toHaveAttribute('aria-checked', 'false')
    await page.getByRole('switch', { name: 'Surprise rewards' }).first().click()
    await page.getByRole('button', { name: 'Save' }).first().click()
    await expect(page.getByText('Add at least one reward to the pool.')).toBeVisible()
    await page.getByLabel(/Add reward to .* pool/).first().fill('Free cookie')
    await page.getByRole('button', { name: 'Add' }).first().click()
    await page.getByRole('button', { name: 'Save' }).first().click()
    await expect(page.getByText('Surprise rewards saved.')).toBeVisible()
    void coffee
    await shot(page, 'p7-07-surprise')
  })
})
